export interface SpaceRecord {
  venueId: string;
  crmVenueId: string | null;
  officialName: string;
  slug: string;
  venueCategory: EventCategory | "MULTI";
  indoorOrOutdoor: "INDOOR" | "OUTDOOR";
  shortDescription: string;
  longDescription: string;
  /** Indicative guest range — provisional, pending verification. */
  guestRange: [number, number] | null;
  capacityByLayout: CapacityByLayout[];
  dimensions: string | null; // null = to be confirmed
  floorArea: string | null;
  ceilingHeight: string | null;
  idealEventTypes: string[];
  seatingLayouts: string[];
  stageDetails: string[];
  avFacilities: string[];
  lightingFacilities: string[];
  greenRooms: string;
  vipFacilities: string[];
  guestEntry: string;
  serviceEntry: string;
  parkingNotes: string;
  accessibility: string;
  restrooms: string;
  floorPlan: string | null;
  heroImage: string;
  /** Optional next/image quality override for the space hero (default 75). */
  heroImageQuality?: number;
  /** Optional custom alt text for the hero image — falls back to the historical generated alt. */
  heroImageAlt?: string;
  /** Placeholder-badge switch for the hero (default true for spaces still on placeholder imagery). */
  heroTag?: boolean;
  /** Optional hero scrim (page-specific readability overlay). */
  heroOverlayClassName?: string;
  gallery: string[];
  /** Optional real-photo alt texts — when present, the gallery renders as the premium real-photo layout. */
  galleryAlts?: string[];
  /** Optional per-space next/image quality override for the gallery (default 92 — unchanged historical behavior). */
  galleryQuality?: number;
  /** Optional gallery layout: "symmetric" (2-col 16:9 grid — default) or "asymmetric" (12-col 7/5 editorial masonry). */
  galleryLayout?: "symmetric" | "asymmetric";
  /** Optional gallery lightbox toggle (default false — preserves historical non-clickable tile behaviour). */
  galleryLightbox?: boolean;
  video: string | null;
  showreel: string | null;
  scenes360: string[];
  /** SAMPLE pricing — pending VIJAYA approval. Prices in INR. */
  pricing: Partial<Record<SlotId, number>> & { fullDay?: number };
  slotRules: string;
  bufferRules: string;
  availabilityEnabled: boolean;
  bookableOnline: boolean;
  requiresManualApproval: boolean;
  allowedAddons: string[];
  relatedSpaces: string[];
}

export interface ComboRule {
  comboSlug: string;
  comboName: string;
  childSlugs: string[];
  /** Relationships stay dormant until operations confirms the real hall relationship. */
  active: boolean;
}

